@pytest.fixture(scope="module")
def sbom_output_path(tmp_path_factory) -> Path:
    """Where this module writes the SBOM it generates, outside the repository."""
    return tmp_path_factory.mktemp("sbom") / "sbom.cdx.json"


@pytest.fixture(scope="module")
def sbom(sbom_output_path) -> dict:
    """Load or generate the SBOM once for all tests in this module."""
    data, source = _load_or_generate_sbom(sbom_output_path)
    if data is None:
        pytest.skip(f"SBOM not available: {source}")
    return data


@pytest.fixture(scope="module")
def pyproject_runtime_deps() -> list[str]:
    """Parse the runtime dependency names from pyproject.toml."""
    with open(PYPROJECT, "rb") as f:
        cfg = tomllib.load(f)

    deps = cfg.get("project", {}).get("dependencies", [])
    names = []
    for dep in deps:
        # Extract package name: strip version specifiers and extras
        # e.g. "openai>=1.3.0" -> "openai", "torch>=2.0.0" -> "torch"
        name = dep.split(";")[0].strip()  # drop markers
        name = name.split(">=")[0].split("<=")[0].split("==")[0]
        name = name.split(">")[0].split("<")[0].split("!=")[0]
        name = name.split("[")[0].strip()  # drop extras
        # Normalize: lowercase, replace - with _
        name = name.lower().replace("-", "_")
        if name:
            names.append(name)
    return names


# ---------------------------------------------------------------------------
# Schema compliance tests
# ---------------------------------------------------------------------------


class TestSBOMSchemaCompliance:
    """The SBOM must conform to CycloneDX JSON schema."""

    def test_bom_format_is_cyclonedx(self, sbom):
        assert (
            sbom.get("bomFormat") == "CycloneDX"
        ), f"bomFormat must be 'CycloneDX', got: {sbom.get('bomFormat')}"

    def test_spec_version_present(self, sbom):
        spec = sbom.get("specVersion")
        assert spec is not None, "specVersion field is missing"
        # Accept 1.4, 1.5, 1.6
        major, minor = str(spec).split(".")[:2]
        assert int(major) >= 1 and int(minor) >= 4, f"specVersion must be >= 1.4, got: {spec}"

    def test_serial_number_present(self, sbom):
        sn = sbom.get("serialNumber") or sbom.get("version")
        assert sn is not None, "SBOM must have a serialNumber or version field"

    def test_metadata_present(self, sbom):
        assert "metadata" in sbom, "SBOM must have a metadata section"

    def test_components_present(self, sbom):
        comps = sbom.get("components", [])
        assert len(comps) > 0, "SBOM must contain at least one component"

    def test_components_have_name_and_version(self, sbom):
        """Every component must have a name; warn if version is missing."""
        comps = sbom.get("components", [])
        missing_name = [c for c in comps if not c.get("name")]
        missing_version = [c.get("name") for c in comps if not c.get("version")]
        assert len(missing_name) == 0, f"{len(missing_name)} components are missing a 'name' field"
        if missing_version:
            # This is a warning, not a failure — some components lack a published version
            import warnings

            warnings.warn(
                f"{len(missing_version)} SBOM components are missing a version: "
                f"{missing_version[:10]}{'...' if len(missing_version) > 10 else ''}",
                stacklevel=2,
            )

    def test_components_have_type(self, sbom):
        """Components should declare their type."""
        comps = sbom.get("components", [])
        with_type = [c for c in comps if c.get("type")]
        # At least 80% should have a type
        if comps:
            pct = len(with_type) / len(comps)
            assert (
                pct >= 0.5
            ), f"Only {pct:.0%} of SBOM components have a 'type' field (expected >= 50%)"

    def test_sbom_validates_against_cyclonedx_schema(self, sbom):
        """The SBOM must validate against the official CycloneDX JSON schema.

        Field-presence checks are not enough — this runs the SBOM through the
        strict CycloneDX JSON schema validator bundled with cyclonedx-python-lib
        (a dependency of cyclonedx-bom). This is the exit criterion:
        "SBOM generates and validates against CycloneDX schema."
        """
        try:
            from cyclonedx.schema import SchemaVersion
            from cyclonedx.validation.json import JsonStrictValidator
        except ImportError:
            pytest.skip("cyclonedx-python-lib not installed; install cyclonedx-bom")

        spec = str(sbom.get("specVersion"))
        version_map = {
            "1.4": SchemaVersion.V1_4,
            "1.5": SchemaVersion.V1_5,
            "1.6": SchemaVersion.V1_6,
        }
        schema_version = version_map.get(spec)
        assert schema_version is not None, f"Unsupported specVersion for validation: {spec}"

        validator = JsonStrictValidator(schema_version)
        errors = validator.validate_str(json.dumps(sbom))
        assert errors is None, f"SBOM failed CycloneDX {spec} schema validation: {errors}"


