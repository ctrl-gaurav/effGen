"""
tests/security/test_sbom.py

Validates that a generated CycloneDX SBOM:
  1. Is schema-compliant (has required top-level fields).
  2. Contains every runtime dependency declared in pyproject.toml.
  3. All components have a name and version.

These tests can run in two modes:
  - With an existing sbom.cdx.json (generated by CI or manually).
  - By invoking cyclonedx-bom on the fly (if installed).

If neither is available the tests that need a real SBOM are skipped.
"""

import json
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

REPO_ROOT = Path(__file__).resolve().parents[2]
PYPROJECT = REPO_ROOT / "pyproject.toml"
DEFAULT_SBOM_PATH = REPO_ROOT / "sbom.cdx.json"


# ---------------------------------------------------------------------------
# SBOM generation helper
# ---------------------------------------------------------------------------


def _generate_sbom(output_path: Path) -> bool:
    """
    Generate a CycloneDX SBOM using cyclonedx-py CLI.
    Returns True on success.
    """
    cyclonedx = shutil.which("cyclonedx-py") or shutil.which("cyclonedx-bom")
    if cyclonedx is None:
        # Try the Python module path
        result = subprocess.run(
            [sys.executable, "-m", "cyclonedx_py.client", "--help"],
            capture_output=True,
        )
        if result.returncode != 0:
            return False
        cyclonedx_cmd = [sys.executable, "-m", "cyclonedx_py.client"]
    else:
        cyclonedx_cmd = [cyclonedx]

    result = subprocess.run(
        cyclonedx_cmd
        + [
            "environment",
            "--of",
            "json",  # cyclonedx-py 7.x uses --of instead of --output-format
            "--sv",
            "1.5",  # --sv instead of --schema-version
            "-o",
            str(output_path),
        ],
        capture_output=True,
        text=True,
    )
    return result.returncode == 0 and output_path.exists()


def _load_or_generate_sbom(output_path: Path) -> tuple[dict | None, str]:
    """
    Load an existing SBOM or generate one. Returns (sbom_dict, source_path).
    Returns (None, reason) if unavailable.

    A generated SBOM is written to *output_path*, which is never inside the
    repository: ``dist/`` is what a release uploads, and a file a test run left
    there would be published beside the wheel.
    """
    # CI generates one at the repository root before the tests run
    if DEFAULT_SBOM_PATH.exists():
        try:
            with open(DEFAULT_SBOM_PATH) as f:
                return json.load(f), str(DEFAULT_SBOM_PATH)
        except (json.JSONDecodeError, OSError):
            pass

    # Try generating on the fly
    if _generate_sbom(output_path):
        try:
            with open(output_path) as f:
                return json.load(f), str(output_path)
        except (json.JSONDecodeError, OSError):
            pass

    return None, "cyclonedx-bom not available and no pre-generated sbom.cdx.json found"


