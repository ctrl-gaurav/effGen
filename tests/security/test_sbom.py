class TestSBOMDependencyCoverage:
    """The SBOM must cover all runtime dependencies from pyproject.toml."""

    def test_sbom_covers_core_runtime_deps(self, sbom, pyproject_runtime_deps):
        """Core runtime deps from pyproject.toml must appear in the SBOM."""
        comp_names = {
            c["name"].lower().replace("-", "_") for c in sbom.get("components", []) if c.get("name")
        }

        # High-value deps we absolutely must track
        critical_deps = [
            "fastapi",
            "pydantic",
            "openai",
            "requests",
            "httpx",
            "aiohttp",
            "click",
            "rich",
        ]
        missing_critical = [d for d in critical_deps if d not in comp_names]
        assert len(missing_critical) == 0, (
            f"Critical deps missing from SBOM: {missing_critical}\n"
            f"SBOM has {len(comp_names)} components"
        )

    def test_sbom_size_reasonable(self, sbom):
        """A real environment install should produce > 50 components."""
        comps = sbom.get("components", [])
        assert (
            len(comps) >= 50
        ), f"SBOM has only {len(comps)} components — expected >= 50 for a full install"

    def test_pyproject_deps_in_sbom(self, sbom, pyproject_runtime_deps):
        """At least 70% of pyproject runtime deps appear in the SBOM."""
        comp_names = {
            c["name"].lower().replace("-", "_") for c in sbom.get("components", []) if c.get("name")
        }

        present = [d for d in pyproject_runtime_deps if d in comp_names]
        missing = [d for d in pyproject_runtime_deps if d not in comp_names]
        coverage = len(present) / len(pyproject_runtime_deps) if pyproject_runtime_deps else 1.0

        # Log which are missing for visibility
        if missing:
            import warnings

            warnings.warn(
                f"pyproject deps not in SBOM ({len(missing)}): {missing}",
                stacklevel=2,
            )

        assert coverage >= 0.70, (
            f"SBOM coverage of pyproject runtime deps is only {coverage:.0%} "
            f"(missing: {missing})"
        )


# ---------------------------------------------------------------------------
# Generation test — invoke cyclonedx-bom and check output
# ---------------------------------------------------------------------------


class TestSBOMGeneration:
    """Test that we can generate a fresh SBOM from the current environment."""

    def test_cyclonedx_bom_installed(self):
        """cyclonedx-bom or cyclonedx-py must be importable."""
        try:
            import cyclonedx_py  # noqa: F401
        except ImportError:
            try:
                import cyclonedx  # noqa: F401
            except ImportError:
                pytest.skip("cyclonedx_py not installed; install with: pip install cyclonedx-bom")

    def test_generate_sbom_produces_valid_json(self, tmp_path):
        """Generate SBOM into a temp file and validate it's parseable."""
        out = tmp_path / "test-sbom.cdx.json"
        generated = _generate_sbom(out)
        if not generated:
            pytest.skip("cyclonedx-bom CLI not available")

        assert out.exists(), "SBOM file was not created"
        with open(out) as f:
            sbom = json.load(f)
        assert sbom.get("bomFormat") == "CycloneDX"
        assert len(sbom.get("components", [])) > 0

    def test_generated_sbom_is_saved_outside_the_repository(self, sbom_output_path):
        """A generated SBOM is kept where a release upload cannot pick it up."""
        if not sbom_output_path.exists():
            success = _generate_sbom(sbom_output_path)
            if not success:
                pytest.skip("Could not generate SBOM — cyclonedx-bom not available")
        assert sbom_output_path.exists(), f"SBOM output not found at {sbom_output_path}"
        assert REPO_ROOT not in sbom_output_path.parents, sbom_output_path
        with open(sbom_output_path) as f:
            sbom = json.load(f)
        assert sbom.get("bomFormat") == "CycloneDX"
