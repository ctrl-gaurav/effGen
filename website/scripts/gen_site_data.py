def _example_arguments(md) -> tuple[dict, str]:
    """The arguments to show in a tool's snippet, taken from the tool itself.

    A tool's metadata carries its own worked examples, and where it does, the
    first one is the call the gallery shows — the values come from whoever wrote
    the tool, not from whoever wrote the page. Those examples also carry the
    output they produced, under an ``output`` key; that is illustrative and is
    dropped here, because the site shows output it ran for itself or none at
    all.

    A tool with no example falls back to its required parameters, filled from
    the schema: the first allowed value of an enum, or a placeholder named after
    the type. The second return value says which of the two happened, so the
    page can mark a snippet whose arguments are placeholders rather than
    presenting it as a call that would run.
    """
    placeholders = {
        "string": "...",
        "integer": 1,
        "number": 1,
        "boolean": True,
        "array": [],
        "object": {},
    }

    example = (md.examples or [None])[0]
    if isinstance(example, dict):
        args = {k: v for k, v in example.items() if k != "output"}
        if args:
            return args, "tool"

    args = {}
    for spec in md.parameters or []:
        if not spec.required:
            continue
        if spec.enum:
            args[spec.name] = spec.enum[0]
        else:
            kind = getattr(spec.type, "value", str(spec.type))
            args[spec.name] = placeholders.get(kind, "...")
    return args, "schema"


def collect_tools() -> dict:
    """Every built-in tool, with the category it is filed under.

    The gallery on the site renders straight from this, so the description, the
    parameter table and the arguments in the snippet are all the tool's own
    metadata rather than a paraphrase of it.
    """
    from effgen.tools import get_registry

    registry = get_registry()
    registry.discover_builtin_tools()
    metadata = registry.get_all_metadata()

    tools = []
    for name in sorted(metadata):
        md = metadata[name]
        cls = type(registry.get_tool_sync(name))
        tools.append(
            {
                "name": name,
                "class_name": cls.__name__,
                "module": cls.__module__,
                "category": getattr(md.category, "value", str(md.category)),
                "description": md.description,
                "tags": list(md.tags or []),
                "requires_api_key": bool(md.requires_api_key),
                "requires_auth": bool(md.requires_auth),
                "requires_approval": bool(md.requires_approval),
                "cost_estimate": md.cost_estimate,
                "timeout_seconds": md.timeout_seconds,
                "parameters": len(md.parameters or []),
                "params": [
                    {
                        "name": spec.name,
                        "type": getattr(spec.type, "value", str(spec.type)),
                        "required": bool(spec.required),
                        "default": spec.default,
                        "enum": list(spec.enum) if spec.enum else None,
                        "description": spec.description,
                    }
                    for spec in md.parameters or []
                ],
                "example_arguments": _example_arguments(md)[0],
                "example_source": _example_arguments(md)[1],
            }
        )

    categories: dict[str, list[str]] = {}
    for tool in tools:
        categories.setdefault(tool["category"], []).append(tool["name"])

    return {
        "count": len(tools),
        "categories": {k: categories[k] for k in sorted(categories)},
        "category_counts": {k: len(categories[k]) for k in sorted(categories)},
        "items": tools,
    }


def collect_presets() -> dict:
    """Every preset, with the tool-schema cost of using it.

    ``approx_tokens_per_call`` is what ``effgen presets`` prints as
    ``~N tok/call``: the size of the tool schemas sent on every request. It is
    the figure that decides whether a preset fits a small-context or
    rate-limited model, so the gallery shows it beside the tool count.
    """
    from effgen.presets import get_preset, list_presets
    from effgen.presets.registry import preset_tool_overhead

    names = list(list_presets())
    items = []
    for name in names:
        preset = get_preset(name)
        _, approx_tokens = preset_tool_overhead(name)
        items.append(
            {
                "name": preset.name,
                "description": preset.description,
                "tools": list(preset.tool_names or []),
                "tool_count": len(preset.tool_names or []),
                "approx_tokens_per_call": approx_tokens,
                "temperature": preset.temperature,
                "max_iterations": preset.max_iterations,
                "enable_memory": bool(preset.enable_memory),
                "enable_sub_agents": bool(preset.enable_sub_agents),
                "tags": list(preset.tags or []),
            }
        )
    return {"count": len(items), "items": items}


def collect_prompts() -> dict:
    """Two distinct surfaces, and the site has to say which it means.

    ``templates`` counts every registered template. ``library`` counts the
    curated domain prompts that ``effgen prompts list`` shows — a smaller number,
    and the one a reader will see if they run the command.
    """
    from effgen.prompts import create_default_template_manager
    from effgen.prompts.library import registry as library

    templates = create_default_template_manager().list_templates()
    prompts = library.all()

    by_domain: dict[str, list[str]] = {}
    for prompt in prompts:
        by_domain.setdefault(prompt.domain, []).append(prompt.name)

    return {
        "templates": len(templates),
        "library": len(prompts),
        "domains": sorted(library.domains()),
        "domain_counts": {k: len(by_domain[k]) for k in sorted(by_domain)},
        "items": [
            {
                "name": p.name,
                "domain": p.domain,
                "variant": p.variant,
                "description": p.description,
                "tags": list(p.tags or []),
                "variables": _template_variables(p),
                "fixture_keys": sorted((p.fixture or {}).keys()),
                "check": _expected_shape(p),
            }
            for p in sorted(prompts, key=lambda p: (p.domain, p.name))
        ],
        "template_names": sorted(templates),
    }


def _template_variables(prompt) -> list[dict]:
    """The inputs a library template renders with, out of its own JSON schema.

    The schema is what ``render()`` validates against, so the gallery's variable
    table cannot drift from what the template will actually accept.
    """
    schema = prompt.input_schema or {}
    required = set(schema.get("required") or ())
    out = []
    for name, spec in (schema.get("properties") or {}).items():
        out.append(
            {
                "name": name,
                "type": spec.get("type", "string"),
                "required": name in required,
                "description": spec.get("description", ""),
                "enum": list(spec["enum"]) if spec.get("enum") else None,
            }
        )
    return out


def _expected_shape(prompt) -> str:
    """How a template's output is checked: as JSON, against a regex, or by a function."""
    shape = prompt.expected_shape or {}
    kind = shape.get("type")
    if kind == "callable":
        return "function"
    return str(kind) if kind else "none"


def collect_models() -> dict:
    """Provider adapters, and the catalog each one ships.

    Ten adapters are registered. Nine of them carry a bundled catalog;
    ``openai_compatible`` carries none, because it serves whatever the endpoint
    it is pointed at serves. Both numbers are true and the site has to say which
    one it means, so both are recorded here.
    """
    from effgen.models import _catalog, registry as model_registry

    providers = sorted(model_registry.list_providers())
    per_provider = {p: len(model_registry.list_models(p)) for p in providers}
    with_catalog = [p for p in providers if per_provider[p] > 0]

    # One row per adapter for the provider table: how many models it carries,
    # which one it reaches for when a call names no model, when the catalog was
    # last checked against the provider's live API, and what the catalog says
    # those models can do. `has_credentials()` is deliberately not read — it
    # answers whether *this machine* holds a key, which is not a fact about
    # effGen and must never reach a page.
    from effgen.models.registry import ProviderRegistry

    rows = []
    for name in providers:
        try:
            records = _catalog.list_models(name)
            meta = _catalog.snapshot_meta(name) or {}
            default = _catalog.default_model(name)
        except Exception:  # noqa: BLE001 - an adapter with no bundled catalog
            records, meta, default = [], {}, None

        contexts = [r.context_window for r in records if r.context_window]
        # Which environment variable the adapter reads. That is a fact about
        # effGen, unlike `has_credentials()`, which answers whether *this*
        # machine holds a key and must never reach a page.
        env_keys = ProviderRegistry.get_provider_info(name).get("env_keys", [])

        rows.append(
            {
                "name": name,
                "env_keys": list(env_keys),
                "models": len(records),
                "default": default,
                "verified_on": meta.get("verified_on"),
                "source": meta.get("source"),
                "supports_tools": sum(1 for r in records if r.supports_tools),
                "supports_vision": sum(1 for r in records if r.supports_vision),
                "supports_audio": sum(1 for r in records if r.supports_audio),
                "free_tier": sum(1 for r in records if r.free_tier),
                "priced": sum(1 for r in records if r.is_priced),
                "max_context": max(contexts) if contexts else None,
            }
        )

    totals = {
        key: sum(row[key] for row in rows)
        for key in ("supports_tools", "supports_vision", "supports_audio", "free_tier", "priced")
    }

    return {
        "adapters": providers,
        "adapter_count": len(providers),
        "with_catalog": with_catalog,
        "with_catalog_count": len(with_catalog),
        "models": sum(per_provider.values()),
        "models_by_provider": per_provider,
        "providers": rows,
        "capability_totals": totals,
        "local_engines": LOCAL_ENGINES,
    }


# argparse writes a sub-command group into the usage line as a braced list
# followed by an ellipsis: `usage: effgen tools [-h] {list,info,test} ...`. A
# choice-constrained option looks similar (`--kind {run,eval}`) but never carries
# the ellipsis, which is what separates the two.
SUBCOMMAND_GROUP = re.compile(r"\{([a-z0-9_,\-]+)\}\s*(?:\n\s*)?\.\.\.")


def _subcommands(command: str) -> list[str]:
    """The sub-commands one top-level command declares, from its own --help."""
    match = SUBCOMMAND_GROUP.search(_cli(command, "--help"))
    if not match:
        return []
    return [c for c in match.group(1).split(",") if c]


def collect_cli() -> dict:
    """The command surface, parsed out of the real ``--help`` output.

    argparse prints the command list as a single braced group; the per-command
    blurb follows it, indented. Both are read here rather than maintained by
    hand, because the site states the command count in several places.
    """
    root = _cli("--help")

    group = SUBCOMMAND_GROUP.search(root)
    if not group:
        raise RuntimeError("could not find the command group in `effgen --help`")
    commands = [c for c in group.group(1).split(",") if c]

    # The blurb for each command, from the "positional arguments" block. argparse
    # wraps long ones onto continuation lines indented further than the name.
    blurbs: dict[str, str] = {}
    current = None
    for line in root.splitlines():
        head = re.match(r"^    ([a-z][a-z0-9\-]*)\s{2,}(.*)$", line)
        if head and head.group(1) in commands:
            current = head.group(1)
            blurbs[current] = head.group(2).strip()
        elif current and re.match(r"^\s{20,}\S", line):
            blurbs[current] += " " + line.strip()
        elif line.strip() == "" or line.startswith("options:"):
            current = None

    themes = re.search(r"--theme \{([a-z\-,]+)\}", root)
    shells = re.search(r"--completion \{([a-z,]+)\}", root)

    sub = {c: _subcommands(c) for c in commands}
    sub = {c: v for c, v in sub.items() if v}

    return {
        "commands": [{"name": c, "summary": blurbs.get(c, "")} for c in commands],
        "command_count": len(commands),
        "subcommands": sub,
        "subcommand_count": sum(len(v) for v in sub.values()),
        "global_options": _options(root),
        # The flag tables the product pages render. A page that lists a
        # command's flags shows the command's own help text, so the table and
        # the binary cannot say different things.
        "command_options": {
            "serve": _options(_cli("serve", "--help")),
            "models browse": _options(_cli("models", "browse", "--help")),
            "models info": _options(_cli("models", "info", "--help")),
            "models list": _options(_cli("models", "list", "--help")),
            "eval": _options(_cli("eval", "--help")),
            "compare": _options(_cli("compare", "--help")),
            "battle": _options(_cli("battle", "--help")),
            "cost": _options(_cli("cost", "--help")),
            "loadtest": _options(_cli("loadtest", "--help")),
        },
        # `serve` documents its operational settings as environment variables in
        # an epilog block; they belong in the same table as its flags.
        "serve_env": _env_settings(
            _cli("serve", "--help"), "Operational settings (environment variables):"),
        "themes": themes.group(1).split(",") if themes else [],
        "completion_shells": shells.group(1).split(",") if shells else [],
    }




# An argparse "options:" block. Each entry starts at column 2 with the flag
# spelling; its help text either follows on the same line or is indented under
# it, and wraps at column 24.
_OPTION_HEAD = re.compile(r"^  (-[^\s].*?)(?:  +(.*))?$")


def _join_wrapped(text: str, continuation: str) -> str:
    """Rejoin one wrapped line of argparse help onto the text before it.

    argparse wraps with ``textwrap``, which breaks a hyphenated word after its
    hyphen, so ``gpt-oss-20b`` can arrive as ``gpt-`` and ``oss-20b`` on two
    lines. A line that ends in a hyphen attached to a word is rejoined without
    the space; every other line is rejoined with one.
    """
    if not text:
        return continuation
    if len(text) > 1 and text.endswith("-") and not text[-2].isspace():
        return f"{text}{continuation}"
    return f"{text} {continuation}"


def _options(help_text: str) -> list[dict]:
    """Every option a command declares, read out of its own ``--help``.

    The site shows these as a table, and a table that paraphrases is worse than
    no table because a reader will copy from it. So the rows are the help text,
    not a description of it.
    """
    lines = help_text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.rstrip() == "options:")
    except StopIteration:
        return []

    options: list[dict] = []
    current: dict | None = None
    for line in lines[start + 1:]:
        if line.strip() == "":
            continue
        # A new top-level block (Examples:, Environment:, …) ends the options.
        if line[:1] not in (" ", "\t"):
            break
        head = _OPTION_HEAD.match(line)
        if head and not line.startswith("    "):
            if current:
                options.append(current)
            current = {"name": head.group(1).strip(), "description": (head.group(2) or "").strip()}
            continue
        if current is not None and line.startswith("    "):
            current["description"] = _join_wrapped(current["description"], line.strip())
    if current:
        options.append(current)

    return [o for o in options if o["name"] != "-h, --help"]



# `effgen serve --help` names its operational settings in an epilog block rather
# than as flags, because they are environment variables. They are as much part of
# the command's surface as its four options, so the site shows them in the same
# table shape — and reads them from the same place.
_ENV_HEAD = re.compile(r"^  ([A-Z][A-Z0-9_]*(?:=\S+)?)\s*(.*)$")


def _env_settings(help_text: str, heading: str) -> list[dict]:
    """The environment variables a command documents under ``heading``."""
    lines = help_text.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith(heading))
    except StopIteration:
        return []

    settings: list[dict] = []
    current: dict | None = None
    for line in lines[start + 1:]:
        if line.strip() == "":
            continue
        if line[:1] not in (" ", "\t"):
            break
        head = _ENV_HEAD.match(line)
        if head and not line.startswith("    "):
            name = head.group(1).strip()
            text = (head.group(2) or "").strip()
            # `NAME_A /  help text` continues onto a bare `NAME_B` below it.
            if text.startswith("/"):
                name, text = f"{name} /", text[1:].strip()
            # Two variables that share one line of help are written as
            # `NAME_A /` with `NAME_B` under it; the pair is one entry.
            if current and current["name"].endswith("/") and not text:
                current["name"] = f"{current['name'].rstrip('/ ')} / {name}"
                continue
            if current:
                settings.append(current)
            current = {"name": name, "description": text}
            continue
        if current is not None:
            current["description"] = f"{current['description']} {line.strip()}".strip()
    if current:
        settings.append(current)
    return settings


