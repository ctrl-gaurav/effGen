#!/usr/bin/env python3
"""Derive every count and list the website states, straight from the installed
effGen package, and write them to ``data/effgen.json``.

The site used to type its numbers into JSX, which is how it came to advertise a
tool count, a model count and a version that the framework had moved past. This
script is the replacement: one file on disk, generated by one command, imported
by both codebases.

    python scripts/gen_site_data.py                 # write data/effgen.json
    python scripts/gen_site_data.py --check         # exit 1 if it is stale
    python scripts/gen_site_data.py --stdout        # print, write nothing

Everything here is introspected from the live package or parsed out of the real
``--help`` output, so it cannot drift from what is installed. The one figure that
is a snapshot rather than a computation is the model catalog, which ships with
the package; ``effgen models refresh`` updates it.

Run it with the framework's environment on PATH::

    export PATH=/path/to/your/effgen/env/bin:$PATH   # or activate it however you do
    unset EFFGEN_BASE_URL OPENAI_BASE_URL OPENAI_API_BASE
    python scripts/gen_site_data.py

``--check`` is what CI and the verification wave run: it regenerates in memory
and compares against the checked-in file, ignoring ``derived_at``, so a stale
count fails the build instead of reaching a page.
"""

