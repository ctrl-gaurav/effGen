# The two web surfaces ship as static files inside the package. Everything the
# `/dashboard` page states about them — which panels exist, what the playground
# offers, how large the whole thing is, and how many external hosts it reaches —
# is read off those files rather than described from memory.

# Most panels are a `<section class="panel">`; the SLO and latency pair sit in a
# two-column row as `<div class="panel">`. Both carry the id the jump row links
# to and an `<h2>` naming them, which is what this reads.
_PANEL = re.compile(
    r'<(?:section|div) class="panel[^"]*" id="(panel-[a-z\-]+)"[^>]*>\s*<h2>([^<]+)</h2>')
_NAV = re.compile(r'<a href="#([a-z\-]+)" data-panel-jump="[a-z\-]+">([^<]+)</a>')
# The framework's own test for this (tests/dx/test_dashboard.py
# ::test_no_external_assets) flags absolute and protocol-relative URLs; a
# same-origin path such as "/dashboard/data.json" is fine. Same expression here,
# so the site reports the number that test enforces.
_OFF_HOST = re.compile(r"""https?://[^\s"'()]+|(?<![:\w])//[^\s"'()]+""")


def collect_web() -> dict:
    """The dashboard and the playground, read off the files the package ships."""
    import effgen

    root = Path(effgen.__file__).resolve().parent
    dashboard_html = (root / "dashboard" / "static" / "index.html").read_text()
    playground_html = (root / "playground" / "static" / "index.html").read_text()

    nav = dict(_NAV.findall(dashboard_html))
    panels = [
        {"id": pid, "title": title.strip(), "nav": nav.get(pid, "")}
        for pid, title in _PANEL.findall(dashboard_html)
    ]
    # The summary row and the two-column row are markup, not `panel` sections,
    # so they carry their own ids and are added in the order they appear.
    summary_cards = re.findall(r'<div class="card-label">([^<]+)</div>', dashboard_html)

    files = []
    external: list[str] = []
    loopback: list[str] = []
    for relative in (
        "dashboard/static/index.html",
        "dashboard/static/app.js",
        "dashboard/static/style.css",
        "playground/static/index.html",
        "playground/static/app.js",
        "playground/static/style.css",
        "webui/static/webui.js",
        "webui/static/webui.css",
    ):
        path = root / relative
        text = path.read_text()
        files.append({"file": relative, "bytes": path.stat().st_size})
        for hit in _OFF_HOST.findall(text):
            # A loopback address is this machine, not a third party. The only
            # one in the shipped files is the example endpoint printed inside
            # the playground's copy-as-curl snippet, which is text on the page
            # rather than something the browser fetches.
            bucket = loopback if hit.startswith(("http://127.0.0.1", "http://localhost")) else external
            bucket.append(f"{relative}: {hit}")

    snippet_kinds = re.findall(r'class="snippet-tab[^"]*" data-kind="([a-z]+)"', playground_html)
    modes = re.findall(r'name="mode" value="([a-z]+)"', playground_html)

    return {
        "dashboard": {
            "panels": panels,
            "summary_cards": summary_cards,
            "data_endpoints": [
                "/dashboard/data.json",
                "/dashboard/spans",
                "/dashboard/catalog.json",
                "/dashboard/history.json",
                "/dashboard/topology.json",
            ],
        },
        "playground": {"snippet_kinds": snippet_kinds, "modes": modes},
        "static_files": files,
        "static_bytes": sum(f["bytes"] for f in files),
        # Zero is the claim `/dashboard` makes, and this is the number behind it.
        "external_references": len(external),
        "external_reference_list": external,
        "loopback_references": loopback,
    }


def _summary(obj) -> str:
    """The first sentence of a docstring, as one line."""
    doc = (obj.__doc__ or "").strip()
    if not doc:
        return ""
    first = doc.split("\n\n")[0]
    return " ".join(first.split())


def _fields(cls) -> list[dict]:
    """A dataclass's fields, with the type and the default as written."""
    import dataclasses

    rows = []
    for f in dataclasses.fields(cls):
        if f.default is not dataclasses.MISSING:
            default = repr(f.default)
        elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            default = None
        else:
            default = None
        rows.append(
            {
                "name": f.name,
                "type": str(f.type),
                "default": default,
                "required": f.default is dataclasses.MISSING
                and f.default_factory is dataclasses.MISSING,  # type: ignore[misc]
            }
        )
    return rows


def collect_examples() -> dict:
    """The example programs that ship in the framework repository.

    They are not part of the wheel — ``pyproject.toml`` excludes ``examples*``
    from the packages it builds — so this reads the directory the CLI itself
    resolves, through the CLI's own discovery function rather than a path
    guessed here. Each row carries the first line of the script's docstring, the
    provider or theme its directory groups it under, and whether the script
    parses its own command-line arguments, which is what decides whether
    ``effgen examples run`` can start it.
    """
    import ast

    from effgen.cli.commands.examples import find_examples_dir

    root = find_examples_dir()
    if root is None:
        raise RuntimeError(
            "no examples directory found; run this from a checkout of the "
            "framework, or set EFFGEN_EXAMPLES_DIR"
        )

    groups = {
        "basic": "The shortest path — one agent, one question",
        "tools": "Agents that call tools",
        "advanced": "Streaming, memory, concurrency and multi-agent pipelines",
        "web_retrieval": "The web, the weather and retrieval over your own files",
        "plugins_presets": "Presets, and a tool you wrote yourself",
        "openai": "OpenAI, including the native provider tools",
        "cerebras": "Cerebras, on its free tier",
        "data": "Fetching the data another example reads",
        "utils": "Sweeping a model across settings",
    }

    items = []
    for path in sorted(root.rglob("*.py")):
        if path.name == "__init__.py":
            continue
        source = path.read_text(encoding="utf-8", errors="replace")
        try:
            docstring = ast.get_docstring(ast.parse(source)) or ""
        except SyntaxError:
            docstring = ""
        summary = ""
        for line in docstring.splitlines():
            line = line.strip()
            if line and not line.lower().startswith("effgen —"):
                summary = line
                break
        relative = path.relative_to(root).with_suffix("").as_posix()
        items.append(
            {
                "name": relative,
                "group": relative.split("/")[0],
                "file": f"examples/{path.relative_to(root).as_posix()}",
                "summary": summary,
                "parses_arguments": "argparse" in source,
                "needs_key": relative.split("/")[0] in ("openai", "cerebras"),
            }
        )

    counts: dict[str, int] = {}
    for item in items:
        counts[item["group"]] = counts.get(item["group"], 0) + 1

    return {
        "count": len(items),
        "groups": [
            {"id": group, "what": groups.get(group, ""), "count": counts[group]}
            for group in sorted(counts)
        ],
        "parses_arguments": sum(1 for item in items if item["parses_arguments"]),
        "items": items,
    }


def collect_api() -> dict:
    """The library surface `/agents` documents, read off the classes themselves.

    Every parameter name, type and default on that page is a row from here, so
    a default that changes in the framework changes the page rather than
    silently disagreeing with it.
    """
    import inspect

    from effgen import (
        AgentConfig,
        AgentMiddleware,
        CheckpointStore,
        DropOldest,
        FileCheckpointStore,
        InMemoryCheckpointStore,
        KeepFirstAndLast,
        KeepToolResults,
        LoggingMiddleware,
        OrchestrationPattern,
        SummarizeOldest,
        ToolApprovalMiddleware,
        ToolCall,
        ToolCallList,
    )
    from effgen.core.agent import AgentResponse
    from effgen.tools.base_tool import ToolResult

    hooks = [
        "before_run",
        "after_run",
        "before_model_call",
        "after_model_call",
        "before_tool_call",
        "after_tool_call",
    ]

    return {
        "agent_config": _fields(AgentConfig),
        "agent_response": _fields(AgentResponse),
        "tool_call": _fields(ToolCall),
        "tool_call_list": sorted(
            name
            for name in ("names", "failed", "total", "by_name", "to_list")
            if hasattr(ToolCallList(), name)
        ),
        "tool_result": _fields(ToolResult),
        "middleware_hooks": [
            {
                "name": hook,
                "signature": str(inspect.signature(getattr(AgentMiddleware, hook))).replace(
                    "self, ", ""
                ),
                "what": _summary(getattr(AgentMiddleware, hook)),
            }
            for hook in hooks
        ],
        "middleware_shipped": [
            {"name": cls.__name__, "what": _summary(cls)}
            for cls in (LoggingMiddleware, ToolApprovalMiddleware)
        ],
        "compaction": [
            {
                "name": cls.__name__,
                "what": _summary(cls),
                "parameters": [
                    {
                        "name": name,
                        "default": (
                            repr(param.default)
                            if param.default is not inspect.Parameter.empty
                            else None
                        ),
                    }
                    for name, param in inspect.signature(cls.__init__).parameters.items()
                    if name != "self"
                ],
            }
            for cls in (SummarizeOldest, DropOldest, KeepFirstAndLast, KeepToolResults)
        ],
        "checkpoint_stores": [
            {"name": cls.__name__, "what": _summary(cls)}
            for cls in (FileCheckpointStore, InMemoryCheckpointStore, CheckpointStore)
        ],
        "orchestration_patterns": [pattern.value for pattern in OrchestrationPattern],
    }


def collect_production() -> dict:
    """The operational surface `/production` documents.

    The roles, the metric names and the error classes are read from the
    installed server and observability modules — not from the documentation,
    which is a separate artefact and can lag behind the code.
    """
    import dataclasses
    import importlib

    from effgen import get_guardrail_preset
    from effgen import RateLimitExceeded
    from effgen.models import errors as model_errors

    rbac = importlib.import_module("effgen.server.rbac")
    metrics = importlib.import_module("effgen.observability.metrics")

    roles = []
    for role in rbac.list_roles():
        row = dataclasses.asdict(role) if dataclasses.is_dataclass(role) else dict(role)
        roles.append(
            {
                "name": row["name"],
                "tools": "none" if row.get("deny_tools") else "all",
                "models": sorted(row["allowed_models"]) or "all",
                "max_cost_per_day": row["max_cost_per_day"],
            }
        )

    instruments = []
    for attribute in sorted(dir(metrics)):
        instrument = getattr(metrics, attribute)
        name = getattr(instrument, "name", None)
        if not isinstance(name, str) or not name.startswith("effgen_"):
            continue
        instruments.append(
            {
                "name": name,
                "kind": type(instrument).__name__.replace("Labeled", "").lower(),
                "help": getattr(instrument, "help", ""),
                "labels": list(getattr(instrument, "label_names", ()) or []),
            }
        )
    instruments.sort(key=lambda row: row["name"])

    guardrail_presets = []
    for name in ("minimal", "standard", "strict", "phi"):
        chain = get_guardrail_preset(name)
        guardrail_presets.append(
            {"name": name, "guardrails": [g.name for g in chain.guardrails]}
        )

    # What each typed error is classified as, by running the real classifier
    # over one instance of each — so the table is the behaviour, not a summary
    # of it.
    error_classes = []
    for cls in (
        model_errors.ModelAuthError,
        model_errors.ModelNotFoundError,
        RateLimitExceeded,
        model_errors.ModelTimeoutError,
        model_errors.ProviderTransientError,
        model_errors.ModelRefusalError,
        model_errors.InvalidRequestError,
        model_errors.BackendUnreachableError,
    ):
        classified = model_errors.classify_provider_error(cls("x"))
        error_classes.append(
            {
                "name": cls.__name__,
                "category": classified.category,
                "should_retry": bool(classified.should_retry),
            }
        )

    return {
        "rbac_roles": roles,
        "metrics": instruments,
        "guardrail_presets": guardrail_presets,
        "guardrail_positions": [
            position.value
            for position in importlib.import_module("effgen.guardrails").GuardrailPosition
        ],
        "error_classes": error_classes,
        "remediation_categories": list(model_errors.REMEDIATION_BY_CATEGORY),
        "public_endpoints": sorted(
            {
                "/health",
                "/healthz",
                "/livez",
                "/ready",
                "/readyz",
                "/slo",
                "/openapi.json",
                "/docs",
                "/redoc",
            }
        ),
    }


