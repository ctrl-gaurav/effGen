LOCAL_ENGINES = ["transformers", "vllm", "gguf", "mlx"]


def _cli(*args: str) -> str:
    """Run the real `effgen` binary and return its stdout."""
    proc = subprocess.run(
        ["effgen", *args],
        capture_output=True,
        text=True,
        timeout=120,
    )
    if proc.returncode != 0 and not proc.stdout:
        raise RuntimeError(f"effgen {' '.join(args)} failed: {proc.stderr[:400]}")
    return proc.stdout


def collect_version() -> dict:
    from importlib.metadata import metadata, version

    meta = metadata("effgen")
    classifiers = meta.get_all("Classifier") or []
    pythons = sorted(
        c.rsplit(":", 1)[1].strip()
        for c in classifiers
        if c.startswith("Programming Language :: Python :: 3.")
    )
    return {
        "version": version("effgen"),
        "python_versions": pythons,
        "python_requires": meta.get("Requires-Python", ""),
    }


